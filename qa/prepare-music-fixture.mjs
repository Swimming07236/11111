import { writeFile } from 'node:fs/promises';
const sampleRate = 8000;
const count = sampleRate * 180;
const bytes = Buffer.alloc(44 + count * 2);
bytes.write('RIFF', 0); bytes.writeUInt32LE(bytes.length - 8, 4); bytes.write('WAVEfmt ', 8);
bytes.writeUInt32LE(16, 16); bytes.writeUInt16LE(1, 20); bytes.writeUInt16LE(1, 22);
bytes.writeUInt32LE(sampleRate, 24); bytes.writeUInt32LE(sampleRate * 2, 28);
bytes.writeUInt16LE(2, 32); bytes.writeUInt16LE(16, 34); bytes.write('data', 36); bytes.writeUInt32LE(count * 2, 40);
for (let i = 0; i < count; i++) bytes.writeInt16LE(Math.round(Math.sin(i / sampleRate * Math.PI * 440) * 25), 44 + i * 2);
await writeFile(new URL('../public/assets/qa-music.wav', import.meta.url), bytes);
